@dataclass
class ComponentInfo:
    available: bool
    words: int = 0
    chunks: int = 0
    note: str | None = None  # why it's unavailable, shown in the UI


@dataclass
class SemanticConsistencyResult:
    code_report: float | None
    code_transcript: float | None
    report_transcript: float | None
    overall: float | None
    # "consistent" | "review_recommended" | "limited_data" | "unavailable" | "disabled"
    status: str
    reason: str
    threshold: float
    model: str = MODEL_NAME
    warning: str | None = None
    components: dict[str, ComponentInfo] = field(default_factory=dict)
    # How the report text was obtained (document_extraction.ReportExtraction.meta()).
    report_extraction: dict | None = None

    def to_dict(self) -> dict:
        return asdict(self)


def _join_labels(labels: list[str]) -> str:
    return labels[0] if len(labels) == 1 else ", ".join(labels[:-1]) + " and " + labels[-1]


def _review_reason(scores: dict[tuple[str, str], float], threshold: float) -> str:
    low = [pair for pair, s in scores.items() if s < threshold]
    if len(scores) == 3 and len(low) == 3:
        detail = "The code documentation, report and video transcript describe substantially different content."
    elif len(low) == 2:
        (a1, b1), (a2, b2) = low
        odd = ({a1, b1} & {a2, b2}).pop()
        others = [COMPONENT_LABELS[c] for c in (a1, b1, a2, b2) if c != odd]
        detail = (f"The submitted {COMPONENT_LABELS[odd]} shows limited semantic overlap with the "
                  f"{_join_labels(others)}.")
    else:
        a, b = (low or [min(scores, key=scores.get)])[0]
        detail = f"The submitted {COMPONENT_LABELS[a]} and {COMPONENT_LABELS[b]} show limited semantic overlap."
    return f"{detail} Some submitted components may describe different content. Review recommended."


def check_semantic_consistency(
    *,
    report_extraction: dict | None = None,
    report_unavailable_note: str | None = None,
    **kwargs,
) -> SemanticConsistencyResult:
    """Compare whichever of the three components contain meaningful text.
    Never raises; every failure becomes an "unavailable" result with a
    warning and no scores.

    ``report_extraction`` is the MarkItDown extraction metadata, attached
    to the result so the instructor can see how the report text was
    obtained; ``report_unavailable_note`` explains a submitted report that
    yielded no text (e.g. extraction failed)."""
    result = _check(report_unavailable_note=report_unavailable_note, **kwargs)
    result.report_extraction = report_extraction
    if report_extraction and report_extraction.get("status") not in (None, "ok"):
        note = (f"Report text extraction was unavailable ({report_extraction.get('status')}: "
                f"{report_extraction.get('error')}); comparisons involving the report were not evaluated.")
        result.warning = f"{result.warning} {note}" if result.warning else note
    return result


def _check(
    *,
    report_unavailable_note: str | None = None,
    code_documentation: str | None,
    report_text: str | None,
    transcript: str | None,
    code_submitted: bool = True,
    report_submitted: bool = True,
    video_submitted: bool = True,
    transcript_backend: str | None = None,
    service: SentenceEmbeddingService | None = None,
    threshold: float | None = None,
) -> SemanticConsistencyResult:
    """Compare whichever of the three components contain meaningful text.
    Never raises; every failure becomes an "unavailable" result with a
    warning and no scores."""
    service = service or get_consistency_service()
    threshold = consistency_threshold() if threshold is None else threshold

    def empty(status: str, reason: str, warning: str | None = None, components=None):
        return SemanticConsistencyResult(None, None, None, None, status, reason, threshold,
                                         warning=warning, components=components or {})

    texts = {"code": clean_text(code_documentation), "report": clean_text(report_text),
             "transcript": clean_text(transcript)}
    components: dict[str, ComponentInfo] = {}
    for name, text in texts.items():
        words = len(text.split())
        if words >= MIN_WORDS:
            components[name] = ComponentInfo(available=True, words=words)
            continue
        if name == "code":
            note = "No code submitted" if not code_submitted else "No code documentation found"
        elif name == "report":
            note = ("Report not submitted" if not report_submitted
                    else report_unavailable_note or "Report unavailable (no extractable text)")
        else:
            if not video_submitted:
                note = "No video submitted"
            elif transcript_backend == "null":
                note = "Transcript unavailable (speech-to-text not configured)"
            else:
                note = "Transcript unavailable (no speech detected)"
        if 0 < words < MIN_WORDS:
            note += f" -- only {words} word(s), too little to compare"
        components[name] = ComponentInfo(available=False, words=words, note=note)

    if not service.enabled:
        return empty("disabled", "Cross-modal semantic analysis is disabled (CROSS_MODAL_SEMANTIC=0).",
                     components=components)

    available = [n for n, c in components.items() if c.available]
    if len(available) < 2:
        missing = "; ".join(c.note for c in components.values() if not c.available)
        return empty("limited_data",
                     f"Fewer than two components contain enough text to compare ({missing}). "
                     "Nothing was evaluated; this is not a low score.",
                     components=components)

    if not service.load():
        return empty("unavailable", "Cross-modal semantic analysis could not run.",
                     warning=f"The sentence-embedding model could not be loaded ({service.error}). "
                             "The rest of the evaluation is unaffected.",
                     components=components)
    try:
        embeddings = service.embed_documents({n: texts[n] for n in available})
    except Exception as exc:
        log.warning("Cross-modal semantic inference failed: %s", exc)
        return empty("unavailable", "Cross-modal semantic analysis could not run.",
                     warning=f"Embedding failed ({exc.__class__.__name__}: {exc}). No similarity score was "
                             "produced; the rest of the evaluation is unaffected.",
                     components=components)

    for name, emb in embeddings.items():
        components[name].chunks = emb.chunk_count

    import numpy as np

    scores: dict[tuple[str, str], float] = {}
    for a, b in PAIRS:
        if a in embeddings and b in embeddings:
            cos = float(np.dot(embeddings[a].vector, embeddings[b].vector))
            scores[(a, b)] = round(max(0.0, min(1.0, cos)), 4)
    overall = round(sum(scores.values()) / len(scores), 4)

    if overall < threshold:
        status, reason = "review_recommended", _review_reason(scores, threshold)
    elif len(available) == 3:
        status = "consistent"
        reason = ("The submitted code documentation, report, and video transcript show a high degree of "
                  "semantic consistency.")
    else:
        status = "limited_data"
        missing = next(c.note for c in components.values() if not c.available)
        a, b = available
        reason = (f"Only the {COMPONENT_LABELS[a]} and {COMPONENT_LABELS[b]} could be compared; they appear "
                  f"semantically consistent. {missing}.")

    return SemanticConsistencyResult(
        code_report=scores.get(("code", "report")),
        code_transcript=scores.get(("code", "transcript")),
        report_transcript=scores.get(("report", "transcript")),
        overall=overall, status=status, reason=reason, threshold=threshold, components=components,
    )
