"""
Cross-modal SEMANTIC consistency: does the student's code documentation,
written report and video transcript describe the same project?

Each available component is turned into one meaning vector with a local
sentence-embedding model (``sentence-transformers/all-MiniLM-L6-v2``), and
the three pairs are compared with cosine similarity:

    code documentation <-> report
    code documentation <-> video transcript
    report             <-> video transcript

Because the model compares meaning rather than words, different wording
for the same idea still scores high -- unlike the keyword-overlap check in
``cross_modal.py``, which stays in place as a separate, auditable signal.

Inputs, all reused from the rest of the pipeline where they exist:

- code documentation: docstrings and comments only (``extract_code_documentation``),
  never the code itself -- this checks whether the student's *explanation*
  matches the other two components;
- report: the text ``report_analysis.extract_report`` already produced;
- transcript: the text the video stage already transcribed (nothing is
  transcribed a second time).

Long documents are never truncated: text is split into sentence-aligned
chunks that fit the model, every chunk is embedded, and the document's
vector is the length-weighted mean of its chunk vectors. Chunk embeddings
are cached by content hash, so re-evaluating a submission (or text shared
between submissions, like a course template) reuses earlier work.

THIS IS A REVIEW SIGNAL ONLY. A low score says "these components may
describe different content -- worth a lecturer's look"; it never deducts
marks and is not evidence of plagiarism or misconduct. A missing component
is reported as unavailable (``None``), never as a 0% score, and never
causes a flag by itself.

Configuration (environment variables):

- ``CROSS_MODAL_SEMANTIC=0`` disables the feature entirely.
- ``CROSS_MODAL_CONSISTENCY_THRESHOLD`` (default 0.50): an overall score
  below this is marked "review recommended". The default is a prototype
  value and has NOT been validated on real student submissions.
"""

from __future__ import annotations

import ast
import hashlib
import io
import logging
import os
import re
import threading
import tokenize
from collections import Counter, OrderedDict
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Callable, Protocol

log = logging.getLogger(__name__)

MODEL_NAME = "sentence-transformers/all-MiniLM-L6-v2"
DEFAULT_THRESHOLD = 0.50
# all-MiniLM-L6-v2 reads at most 256 word pieces (it was trained on 128);
# ~120 words stays inside that for ordinary English prose.
CHUNK_WORDS = 120
# Fewer words than this isn't enough meaning to compare reliably.
MIN_WORDS = 5

COMPONENT_LABELS = {
    "code": "code documentation",
    "report": "report",
    "transcript": "video transcript",
}
PAIRS = (("code", "report"), ("code", "transcript"), ("report", "transcript"))


def consistency_threshold() -> float:
    raw = os.environ.get("CROSS_MODAL_CONSISTENCY_THRESHOLD")
    if raw is None or not raw.strip():
        return DEFAULT_THRESHOLD
    try:
        value = float(raw)
    except ValueError:
        log.warning("Ignoring invalid CROSS_MODAL_CONSISTENCY_THRESHOLD=%r", raw)
        return DEFAULT_THRESHOLD
    return min(1.0, max(0.0, value))


def _feature_enabled() -> bool:
    return os.environ.get("CROSS_MODAL_SEMANTIC", "1").strip().lower() not in {"0", "false", "no", "off"}


# --------------------------------------------------------------------------
# Code documentation extraction
# --------------------------------------------------------------------------

_HASH_LANGS = {".py", ".rb", ".sh", ".r", ".pl", ".yaml", ".yml"}
_C_LANGS = {".java", ".js", ".jsx", ".ts", ".tsx", ".c", ".h", ".cpp", ".hpp", ".cc", ".cs",
            ".go", ".rs", ".kt", ".swift", ".php", ".scala"}
CODE_EXTENSIONS = _HASH_LANGS | _C_LANGS

_STRINGS = r'"(?:\\.|[^"\\\n])*"|\'(?:\\.|[^\'\\\n])*\''
_C_COMMENT_RE = re.compile(rf"(?P<s>{_STRINGS}|`(?:\\.|[^`\\])*`)|(?P<line>//[^\n]*)|(?P<block>/\*[\s\S]*?\*/)")
_HASH_COMMENT_RE = re.compile(rf'(?P<s>"""[\s\S]*?"""|\'\'\'[\s\S]*?\'\'\'|{_STRINGS})|(?P<line>#[^\n]*)')

# Tool directives, license headers and similar lines that carry no
# description of the project.
_BOILERPLATE_RE = re.compile(
    r"^(-\*-|coding[:=]|noqa|type:\s*ignore|pylint:|pyright:|mypy:|fmt:|isort:|"
    r"eslint|@ts-|prettier-ignore|istanbul|jshint|tslint|#?region\b|#?endregion\b|"
    r"spdx-license|copyright\b|\(c\)|all rights reserved|licensed under|"
    r"generated by|auto-?generated|do not edit)",
    re.IGNORECASE,
)
_TAG_PREFIX_RE = re.compile(r"^(todo|fixme|note|hack|xxx)\b[:\s-]*", re.IGNORECASE)
_CODE_CHARS = set("(){}[];=<>+*&|")


def _clean_comment(text: str) -> str:
    """Strip comment markers and drop lines that aren't prose: tool
    directives, licence boilerplate, separators, commented-out code."""
    kept: list[str] = []
    for line in text.splitlines():
        if line.strip().startswith("#!"):
            continue  # shebang
        line = line.strip().lstrip("/*#").rstrip("*/").strip()
        line = _TAG_PREFIX_RE.sub("", line)
        if not line or _BOILERPLATE_RE.match(line):
            continue
        letters = sum(c.isalpha() for c in line)
        if letters < 3 or len(re.findall(r"[A-Za-z]{2,}", line)) < 2:
            continue  # separators, "----", lone identifiers
        if sum(c in _CODE_CHARS for c in line) / len(line) > 0.12 or line.endswith((";", "{", "}")):
            continue  # commented-out code
        kept.append(line)
    return " ".join(kept)


def _python_documentation(source: str) -> list[str]:
    """Docstrings via ``ast`` (so ordinary string literals aren't
    mistaken for documentation) plus ``#`` comments via ``tokenize``."""
    tree = ast.parse(source)
    parts = []
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            doc = ast.get_docstring(node)
            if doc:
                parts.append(doc)
    for tok in tokenize.generate_tokens(io.StringIO(source).readline):
        if tok.type == tokenize.COMMENT:
            parts.append(tok.string)
    return parts


def extract_documentation(source: str, filename: str) -> str:
    """Natural-language documentation from one source file: docstrings
    and comments only, cleaned of markers and boilerplate."""
    ext = Path(filename).suffix.lower()
    parts: list[str] = []
    if ext == ".py":
        try:
            parts = _python_documentation(source)
        except (SyntaxError, tokenize.TokenError, IndentationError, ValueError):
            parts = []
        if not parts:  # unparsable file: fall back to the regex scan below
            parts = [m.group() for m in _HASH_COMMENT_RE.finditer(source)
                     if m.lastgroup == "line" or m.group().startswith(('"""', "'''"))]
            parts = [p.strip("\"'") for p in parts]
    else:
        pattern = _HASH_COMMENT_RE if ext in _HASH_LANGS else _C_COMMENT_RE
        parts = [m.group() for m in pattern.finditer(source) if m.lastgroup in ("line", "block")]
    cleaned = (_clean_comment(p) for p in parts)
    return " ".join(p for p in cleaned if p)


def extract_code_documentation(code_dir: Path) -> str:
    """Documentation across every source file in a submission's code
    directory (recursive), in a stable order."""
    texts = []
    for path in sorted(Path(code_dir).rglob("*")):
        if path.is_file() and path.suffix.lower() in CODE_EXTENSIONS:
            doc = extract_documentation(path.read_text(encoding="utf-8", errors="ignore"), path.name)
            if doc:
                texts.append(doc)
    return "\n".join(texts)


# --------------------------------------------------------------------------
# Text preprocessing + chunking
# --------------------------------------------------------------------------

_PAGE_MARKER_RE = re.compile(r"^\s*(page\s*)?\d{1,4}(\s*(of|/)\s*\d{1,4})?\s*$", re.IGNORECASE)
_TOC_LINE_RE = re.compile(r"\.{4,}\s*\d+\s*$")
_SENTENCE_RE = re.compile(r"(?<=[.!?])\s+(?=[A-Z0-9\"'(])")


def clean_text(text: str | None) -> str:
    """Light cleanup only -- wording is left intact so the model sees the
    real content: rejoin words hyphenated across line breaks, drop page
    numbers, table-of-contents leader lines and running headers/footers
    (short heading-like lines -- under 60 characters, not ending in
    sentence punctuation -- repeated 3+ times), then collapse whitespace.
    Repeated sentences are kept: they're content, not page furniture."""
    if not text:
        return ""
    text = re.sub(r"(\w)-\n(\w)", r"\1\2", text)
    lines = [line.strip() for line in text.splitlines()]
    heading_like = (l for l in lines if l and len(l) < 60 and not l.endswith((".", "!", "?", ",", ";", ":")))
    repeated = {line for line, n in Counter(heading_like).items() if n >= 3}
    kept = [
        line for line in lines
        if line and line not in repeated and not _PAGE_MARKER_RE.match(line) and not _TOC_LINE_RE.search(line)
    ]
    return " ".join(" ".join(kept).split())


def chunk_text(text: str, max_words: int = CHUNK_WORDS) -> list[str]:
    """Split into consecutive chunks of whole sentences, each at most
    ``max_words`` words (an over-long sentence is split on word
    boundaries). Every word lands in exactly one chunk."""
    chunks: list[str] = []
    current: list[str] = []
    for sentence in _SENTENCE_RE.split(text):
        words = sentence.split()
        while len(words) > max_words:
            if current:
                chunks.append(" ".join(current))
                current = []
            chunks.append(" ".join(words[:max_words]))
            words = words[max_words:]
        if current and len(current) + len(words) > max_words:
            chunks.append(" ".join(current))
            current = []
        current.extend(words)
    if current:
        chunks.append(" ".join(current))
    return chunks


# --------------------------------------------------------------------------
# Embedding service: one shared model, chunk cache, never raises
# --------------------------------------------------------------------------


class SentenceEncoder(Protocol):
    def encode(self, texts: list[str]):  # -> numpy array (n, dim), rows L2-normalized
        ...


class MiniLMEncoder:
    """The real encoder. Constructing it loads (and on first use
    downloads, ~90 MB) the model; do this once per process."""

    def __init__(self, model_name: str = MODEL_NAME, device: str = "cpu", batch_size: int = 32):
        from ..model_loading import MODEL_LOAD_LOCK

        # Serialized with the UniXcoder load: importing transformers from two
        # threads at once breaks the other import (see app/model_loading.py).
        with MODEL_LOAD_LOCK:
            from sentence_transformers import SentenceTransformer
            from transformers.utils import logging as hf_logging

            # Quiet the per-weight progress bar and a harmless "UNEXPECTED
            # position_ids" load report while loading.
            verbosity = hf_logging.get_verbosity()
            hf_logging.set_verbosity_error()
            hf_logging.disable_progress_bar()
            try:
                self.model = SentenceTransformer(model_name, device=device)
            finally:
                hf_logging.set_verbosity(verbosity)
                hf_logging.enable_progress_bar()
        self.batch_size = batch_size

    def encode(self, texts: list[str]):
        return self.model.encode(texts, batch_size=self.batch_size, normalize_embeddings=True,
                                 convert_to_numpy=True, show_progress_bar=False)


@dataclass
class DocumentEmbedding:
    vector: "object"  # numpy.ndarray (dim,), L2-normalized
    chunk_count: int
    word_count: int


class SentenceEmbeddingService:
    """Process-wide owner of the sentence-embedding model: loaded at most
    once (thread-safe), chunk embeddings cached in an LRU keyed by a hash
    of the chunk text."""

    def __init__(self, encoder_factory: Callable[[], SentenceEncoder] | None = None,
                 cache_size: int = 20_000, enabled: bool | None = None):
        self._factory = encoder_factory or MiniLMEncoder
        self._encoder: SentenceEncoder | None = None
        self._lock = threading.Lock()
        self._cache: OrderedDict[str, object] = OrderedDict()
        self._cache_size = cache_size
        self.enabled = _feature_enabled() if enabled is None else enabled
        self.status = "not_loaded" if self.enabled else "disabled"  # | ready | unavailable
        self.error: str | None = None
        self.cache_hits = 0
        self.chunks_encoded = 0

    def load(self) -> bool:
        if not self.enabled:
            return False
        with self._lock:
            if self._encoder is not None:
                return True
            if self.status == "unavailable":
                return False
            try:
                self._encoder = self._factory()
                self.status = "ready"
                return True
            except Exception as exc:  # ImportError, download/network errors, ...
                self.status = "unavailable"
                self.error = f"{exc.__class__.__name__}: {exc}"
                log.warning("Cross-modal semantic model unavailable: %s", self.error)
                return False

    def preload_in_background(self) -> threading.Thread | None:
        if not self.enabled:
            return None
        thread = threading.Thread(target=self.load, name="minilm-preload", daemon=True)
        thread.start()
        return thread

    def retry(self) -> None:
        with self._lock:
            if self._encoder is None and self.enabled:
                self.status, self.error = "not_loaded", None

    @staticmethod
    def _key(chunk: str) -> str:
        return hashlib.sha256(f"{MODEL_NAME}|{chunk}".encode()).hexdigest()

    def embed_documents(self, texts: dict[str, str]) -> dict[str, DocumentEmbedding]:
        """Embed already-cleaned documents. All uncached chunks of all
        documents go through the model in one call. Raises on inference
        failure -- ``check_semantic_consistency`` turns that into an
        "unavailable" result."""
        import numpy as np

        plans = {name: chunk_text(text) for name, text in texts.items()}
        missing: dict[str, str] = {}
        with self._lock:
            for chunks in plans.values():
                for chunk in chunks:
                    key = self._key(chunk)
                    if key in self._cache:
                        self._cache.move_to_end(key)
                        self.cache_hits += 1
                    else:
                        missing[key] = chunk
        if missing:
            vectors = np.asarray(self._encoder.encode(list(missing.values())), dtype=float)
            if vectors.shape[0] != len(missing) or not np.all(np.isfinite(vectors)):
                raise ValueError("embedding model returned malformed vectors")
            with self._lock:
                for key, vector in zip(missing, vectors):
                    self._cache[key] = vector
                    self.chunks_encoded += 1
                while len(self._cache) > self._cache_size:
                    self._cache.popitem(last=False)

        out: dict[str, DocumentEmbedding] = {}
        for name, chunks in plans.items():
            with self._lock:
                vecs = [self._cache.get(self._key(c)) for c in chunks]
            if any(v is None for v in vecs):  # evicted mid-call by a huge batch: recompute directly
                vecs = list(np.asarray(self._encoder.encode(chunks), dtype=float))
            weights = np.asarray([len(c.split()) for c in chunks], dtype=float)
            mean = (np.stack(vecs) * weights[:, None]).sum(axis=0) / weights.sum()
            norm = np.linalg.norm(mean)
            out[name] = DocumentEmbedding(vector=mean / norm if norm else mean,
                                          chunk_count=len(chunks), word_count=int(weights.sum()))
        return out


_service: SentenceEmbeddingService | None = None
_service_lock = threading.Lock()


def get_consistency_service() -> SentenceEmbeddingService:
    global _service
    with _service_lock:
        if _service is None:
            _service = SentenceEmbeddingService()
        return _service


def set_consistency_service(service: SentenceEmbeddingService | None) -> None:
    """Swap the process-wide service (tests inject fakes this way)."""
    global _service
    with _service_lock:
        _service = service


